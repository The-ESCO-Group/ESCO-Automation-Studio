export function createDefaultEngine(): ValidationEngine {
  const engine = new ValidationEngine();
  for (const rule of defaultRules) {
    engine.add(rule);
  }
  // Registered at the composition root (not in `defaultRules`) to keep these
  // additions isolated from the concurrently-edited rules.ts.
  engine.add(duplicateProgramParameter);
  engine.add(aliasExternalAccess);
  engine.add(radixDataType);
  engine.add(aoiParameterType);
  engine.add(aoiParameterConstant);
  engine.add(circularAoiReference);
  engine.add(eventTaskTrigger);
  engine.add(moduleSlotConflict);
  engine.add(duplicateModuleName);
  engine.add(moduleParentReference);
  engine.add(unreferencedRoutine);
  engine.add(taskWatchdog);
  engine.add(safetyTask);
  engine.add(safetyProgramScheduling);
  engine.add(safetyTagPartition);
  engine.add(moduleElectronicKeying);
  engine.add(consumedTagRpi);
  engine.add(moduleConnectionRpi);
  engine.add(moduleConnectionInputConfig);
  engine.add(moduleSlotChassisSize);
  engine.add(moduleKeyingRevision);
  engine.add(moduleSafetyNetworkNumber);
  engine.add(continuousTaskConfig);
  engine.add(continuousTaskInhibit);
  engine.add(boolArrayMultiple);
  engine.add(controllerHandlerReference);
  engine.add(taskCapacity);
  engine.add(eventTaskTimeout);
  engine.add(programFolderUsage);
  engine.add(redundancyContinuousTask);
  engine.add(aoiInstructionRestrictions);
  engine.add(aoiCapacity);
  engine.add(aoiLocalTagType);
  engine.add(structuredTextSyntax);
  engine.add(structuredTextReferences);
  engine.add(structuredTextInstructions);
  engine.add(structuredTextCase);
  return engine;
}
